        public static long GetWindowLongPtr(IntPtr hWnd, int nIndex)
        {
            if (IntPtr.Size == 8) return GetWindowLongPtr64(hWnd, nIndex).ToInt64();
            return GetWindowLong32(hWnd, nIndex);
        }

        public static IntPtr SetWindowLongPtr(IntPtr hWnd, int nIndex, long dwNewLong)
        {
            if (IntPtr.Size == 8) return SetWindowLongPtr64(hWnd, nIndex, new IntPtr(dwNewLong));
            return new IntPtr(SetWindowLong32(hWnd, nIndex, unchecked((int)dwNewLong)));
        }

        public static string GetWindowClassName(IntPtr hWnd)
        {
            if (hWnd == IntPtr.Zero) return string.Empty;
            StringBuilder sb = new StringBuilder(256);
            int len = GetClassName(hWnd, sb, sb.Capacity);
            return len > 0 ? sb.ToString() : string.Empty;
        }

        public static uint GetMonitorDpi(int x, int y)
        {
            try
            {
                POINT pt = new POINT { X = x + 8, Y = y + 8 };
                IntPtr mon = MonitorFromPoint(pt, MONITOR_DEFAULTTONEAREST);
                if (mon != IntPtr.Zero)
                {
                    uint dx, dy;
                    if (GetDpiForMonitor(mon, 0, out dx, out dy) == 0 && dx >= 72)
                    {
                        return dx;
                    }
                }
            }
            catch
            {
                // Older Windows without shcore.dll
            }
            return 96;
        }
